import AppKit

// Keep drag decoding separate so Finder's multiple-file payload stays intact.
enum DroppedFiles {
    static func read(from pasteboard: NSPasteboard) -> [URL] {
        let objects = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) ?? []
        return objects.compactMap { ($0 as? NSURL).map { $0 as URL } }
    }
}
